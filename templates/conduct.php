  <h1 class="display">Code of conduct</h1>
  <p class="kicker">500 Lines Media LLC · Last updated: October 25, 2026</p>
  <p>Comic-Subs is a shared workspace for comic makers. Read the board, post work, and use the tools in a way that leaves the next person better off.</p>
  <h2 class="display">Treat people fairly</h2>
  <ul>
    <li>No harassment, slurs, threats, or sexual comments aimed at another person.</li>
    <li>Disagree about the work. Do not attack the person.</li>
    <li>Do not post someone else’s contact details or private messages.</li>
  </ul>
  <h2 class="display">Post honest work</h2>
  <ul>
    <li>Listings must describe real roles, rates, and deadlines as you know them.</li>
    <li>Do not bait creators with fake jobs, unpaid “exposure,” or work you do not intend to hire.</li>
    <li>If a role closes, take the post down or say so.</li>
  </ul>
  <h2 class="display">Respect the art</h2>
  <ul>
    <li>Upload only pages you have the right to process.</li>
    <li>Do not copy another user’s uploads, flats, or overlays and present them as yours.</li>
    <li>Credit collaborators the way you agreed.</li>
  </ul>
  <h2 class="display">If something goes wrong</h2>
  <p>We may remove a post or close an account that breaks these rules. Write to the site operator and include the listing or page involved.</p>
